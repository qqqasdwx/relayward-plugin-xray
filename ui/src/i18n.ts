export type Translator = (message: string, values?: Record<string, string | number>) => string
export function translator(locale: Locale): Translator {
  return (message, values = {}) => {
    let result = locale === "zh-CN" ? zhCN[message] ?? message : message
    for (const [key, value] of Object.entries(values)) result = result.split(`{${key}}`).join(String(value))
    return result
  }
}
